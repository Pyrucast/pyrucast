//! Turn the book's Rust snippets into a compilable test target.
//!
//! `mdbook test` compiles **nothing**: every Rust block of `book/src` is
//! marked `rust,ignore`, so a renamed module or a changed signature can rot
//! there indefinitely. This binary extracts the blocks that are real programs
//! and writes them to `tests/book_blocks.rs`, one function per page, which
//! `script/check_doc.sh` then type-checks.
//!
//! Run with:
//!
//! ```sh
//! cargo run --quiet --bin book_blocks
//! cargo check --test book_blocks --features viz
//! ```
//!
//! **What it selects.** A page qualifies only if at least one of its Rust
//! blocks imports the crate (`use pyrucast::`) — that rules out the design
//! pages, whose blocks are signature sketches, not code. Within a qualifying
//! page it keeps the blocks that import the crate or bind something (`let`),
//! and concatenates them **in reading order** into a single function, so a
//! block that continues the previous one sees its bindings. `use` lines are
//! hoisted to the top and de-duplicated, since the same import often opens
//! several blocks of a page.
//!
//! **What it cannot fix.** The snippets are excerpts: many name a variable the
//! page never defines. Those raise `E0425` and friends, which the checking
//! script ignores — it only fails on the codes that mean the *API itself*
//! moved (unresolved import, unknown method, wrong arity, wrong type). See
//! `script/check_doc.sh` for the exact list.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// One fenced Rust block: its 1-based line number in the page, and its body.
struct Block {
    line: usize,
    code: String,
}

/// Every `*.md` under `dir`, sorted, so the output is deterministic.
fn markdown_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    let mut paths: Vec<PathBuf> = entries.flatten().map(|e| e.path()).collect();
    paths.sort();
    for p in paths {
        if p.is_dir() {
            markdown_files(&p, out);
        } else if p.extension().is_some_and(|e| e == "md") {
            out.push(p);
        }
    }
}

/// The fenced blocks of `text` whose info string starts with `rust`.
fn rust_blocks(text: &str) -> Vec<Block> {
    let mut blocks = Vec::new();
    let mut open: Option<(usize, Vec<&str>)> = None;
    for (i, line) in text.lines().enumerate() {
        match &mut open {
            None => {
                if let Some(info) = line.strip_prefix("```") {
                    if info.trim_end().starts_with("rust") {
                        open = Some((i + 2, Vec::new()));
                    }
                }
            }
            Some((start, buf)) => {
                if line.starts_with("```") {
                    blocks.push(Block {
                        line: *start,
                        code: buf.join("\n"),
                    });
                    open = None;
                } else {
                    buf.push(line);
                }
            }
        }
    }
    blocks
}

/// A block worth compiling: it imports the crate, or binds something.
fn is_program(code: &str) -> bool {
    code.contains("use pyrucast::") || code.lines().any(|l| l.trim_start().starts_with("let "))
}

fn main() -> std::io::Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let mut pages = Vec::new();
    markdown_files(&root.join("book/src"), &mut pages);

    // The whole file hangs off `book-check`, off by default: a plain
    // `cargo test` must not choke on snippets that never type-check alone.
    let mut out = String::from(
        "// GENERATED by `cargo run --bin book_blocks` — do not edit, do not commit.\n\
         // Source: the `rust` code blocks of book/src/**.md. See src/bin/book_blocks.rs.\n\
         // Nothing here is ever *run*: compiling it is the whole point.\n\
         #![cfg(feature = \"book-check\")]\n\n",
    );
    let (mut n_pages, mut n_blocks) = (0usize, 0usize);

    for page in &pages {
        let text = fs::read_to_string(page)?;
        let blocks = rust_blocks(&text);
        if !blocks.iter().any(|b| b.code.contains("use pyrucast::")) {
            continue;
        }
        let kept: Vec<&Block> = blocks.iter().filter(|b| is_program(&b.code)).collect();
        if kept.is_empty() {
            continue;
        }

        let shown = page
            .strip_prefix(root)
            .unwrap_or(page)
            .display()
            .to_string();
        let shown = shown.replace('\\', "/");
        let (mut uses, mut body) = (Vec::new(), Vec::new());
        for b in &kept {
            body.push(format!("    // --- {shown}:{}", b.line));
            // A `use` may span several lines (rustfmt breaks long lists), so
            // swallow lines until the one that closes it. Hoisting half a
            // statement would leave the file unparsable — and an unparsable
            // file is checked for *nothing*.
            let mut pending: Option<String> = None;
            for l in b.code.lines() {
                match &mut pending {
                    Some(acc) => {
                        acc.push('\n');
                        acc.push_str(l);
                        if l.trim_end().ends_with(';') {
                            let done = pending.take().unwrap();
                            if !uses.contains(&done) {
                                uses.push(done);
                            }
                        }
                    }
                    None => {
                        if l.starts_with("use ") {
                            if l.trim_end().ends_with(';') {
                                if !uses.contains(&l.to_string()) {
                                    uses.push(l.to_string());
                                }
                            } else {
                                pending = Some(l.to_string());
                            }
                        } else {
                            body.push(l.to_string());
                        }
                    }
                }
            }
            // An unterminated `use` at the end of a block: keep it verbatim
            // rather than dropping it, so the breakage stays visible.
            if let Some(acc) = pending.take() {
                body.push(acc);
            }
        }

        // The viz layer is behind a feature; a page that uses it only compiles
        // when that feature is on.
        let needs_viz = uses
            .iter()
            .chain(body.iter())
            .any(|l| l.contains("pyrucast::viz"));
        let _ = writeln!(out, "// ===== {shown}");
        if needs_viz {
            let _ = writeln!(out, "#[cfg(feature = \"viz\")]");
        }
        // `rustfmt::skip` keeps `cargo fmt --check` off a generated file whose
        // layout is the book's, not rustfmt's.
        let _ = writeln!(out, "#[rustfmt::skip]");
        let _ = writeln!(out, "#[allow(unused, clippy::all)]");
        let _ = writeln!(
            out,
            "fn page_{n_pages}() -> Result<(), Box<dyn std::error::Error>> {{"
        );
        for u in &uses {
            let _ = writeln!(out, "    {u}");
        }
        for l in &body {
            let _ = writeln!(out, "{l}");
        }
        // Blocks written to live inside a `-> Result` function end on `?`.
        let _ = writeln!(out, "    Ok(())\n}}\n");

        n_pages += 1;
        n_blocks += kept.len();
    }

    // Exactly one trailing newline: rustfmt normalises file-level whitespace
    // even where `rustfmt::skip` protects the items.
    let dest = root.join("tests/book_blocks.rs");
    fs::write(&dest, format!("{}\n", out.trim_end()))?;
    println!("{n_blocks} blocs de {n_pages} pages → tests/book_blocks.rs");
    Ok(())
}
