"""Guards of the reference-element figures of `book/src/elements/img/`.

The SVGs are committed artefacts generated by `script/elements_figures.py`
(see its docstring). Two things can make them lie, and each has a test:

- the **figure is stale**: the script or a node table of a page changed and the
  SVGs were not regenerated → `test_figures_are_up_to_date`;
- the **rule drawn is not the rule computed**: the script rebuilds the Gauss
  points from their closed form, so it must agree with the tables `pyrucast`
  returns → `test_quadrature_matches_pyrucast`.

The node coordinates need no test of their own: the figure is read from the
page's table, so it cannot disagree with it.
"""

import importlib.util
import pathlib
import sys

import pyrucast
import pytest

ROOT = pathlib.Path(__file__).resolve().parents[2]

spec = importlib.util.spec_from_file_location(
    "elements_figures", ROOT / "script" / "elements_figures.py"
)
figures = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = figures  # @dataclass looks its module up there
spec.loader.exec_module(figures)


@pytest.mark.skip
def test_figures_are_up_to_date():
    stale = [
        name
        for name, svg in figures.render_all().items()
        if not (figures.OUT / name).exists()
        or (figures.OUT / name).read_text(encoding="utf-8") != svg
    ]
    assert not stale, f"run `python script/elements_figures.py` ({stale})"


def tables(element, quadrature):
    """(ξ…, w) of every Gauss point of `element`, in a canonical order."""
    figures.load(element)  # the nodes come from the page
    # LAGRANGE1 is the default; the quadratic elements name their interpolation.
    space = pyrucast.FiniteElementSpace(
        pyrucast.Mesh(pyrucast.Coords(element.dim), element.name.upper()),
        **({"interpolation": "LAGRANGE2"} if element.quadratic else {}),
        quadrature=quadrature,
    )[0]
    return canonical(
        (tuple(space.gauss_xi(g)), space.gauss_weight(g))
        for g in range(space.gauss_count)
    )


def canonical(points):
    """Sorted on rounded values — two correct rules differ by 1e-15, not by the order."""
    rows = [(*xi, w) for xi, w in points]
    return sorted(rows, key=lambda r: tuple(round(v, 6) + 0.0 for v in r))


@pytest.mark.parametrize("element", figures.ELEMENTS, ids=lambda e: e.name)
def test_quadrature_matches_pyrucast(element):
    for mine, theirs in (
        (canonical(element.gauss), tables(element, "GAUSS")),
        (canonical([element.reduced]), tables(element, "REDUCED")),
    ):
        assert len(mine) == len(theirs)
        for a, b in zip(mine, theirs):
            assert a == pytest.approx(b, abs=1e-8)
