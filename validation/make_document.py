"""Generate `validation/README.md`, the validation document, from the case data.

Every case folder holds a hand-written `case.toml` (description sheet,
reference values, values printed in the 2011 document) and, once computed,
`results.json` (pyrucast, written by `run_pyrucast.py`) and `castem2026.json`
(Cast3M 2026, written by `run_castem.py`). This script only reads them: every
number of the document comes from one of these files.

Running::

    python validation/make_document.py
"""

import json
import pathlib
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent

HEADER = """\
# Annotated testing files — pyrucast edition

<!-- Generated by validation/make_document.py: do not edit by hand. -->

This document follows, chapter by chapter and case by case, the collection
*Annotated Testing Files* (E. Le Fichoux, ENSTA, 2011, Cast3M documentation).
Each case keeps the original description sheet, cites the same source and
compares with the same reference value. Four values are shown side by side:

- **Reference**: the analytical or benchmark value of the original document
  (or of the Cast3M `.dgibi` file when the document prints none);
- **Cast3M 2011**: the value printed in the 2011 document, as printed;
- **Cast3M 2026**: the value obtained by running the case's `.dgibi` file shipped with
  Cast3M 2026 (`dgibi/<case>.dgibi`), unmodified apart from the lines that
  print the compared quantities;
- **pyrucast**: the value computed by the case's `run.py`.

A case that pyrucast cannot compute yet keeps its sheet and its reference
values; its pyrucast column names the missing features.

Each case lives in its own folder, `<chapter>/<case>/`: `case.toml` (sheet and
reference values), `run.py` (pyrucast script), `results.json` and
`castem2026.json` (computed values), and the figures written by `run.py`.

Regenerating:

```text
python validation/run_pyrucast.py     # pyrucast values and figures
python validation/run_castem.py       # Cast3M 2026 values (needs Cast3M 2026)
python validation/make_document.py    # this document
```
"""


def load_cases():
    """Every case of `index.toml`, in document order, as (chapter, folder, data)."""
    index = tomllib.loads((ROOT / "index.toml").read_text(encoding="utf-8"))
    cases = []
    for chapter in index["chapter"]:
        for name in chapter["cases"]:
            folder = ROOT / chapter["folder"] / name
            data = tomllib.loads((folder / "case.toml").read_text(encoding="utf-8"))
            cases.append((chapter, folder, data))
    return cases


def read_json(path):
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def status(case, folder):
    """`gap` (a pyrucast feature is missing), `run` (computed) or `pending`."""
    if case.get("gap"):
        return "gap"
    if (folder / "results.json").exists():
        return "run"
    return "pending"


def references(case, folder):
    """The reference of each quantity: given in `case.toml`, or computed by the
    Cast3M `.dgibi` file (`reference_probe`, stored in `castem2026.json`)."""
    castem = read_json(folder / "castem2026.json") or {}
    computed = castem.get("references", {})
    refs = {}
    for q in case.get("quantity", []):
        if "reference" in q:
            refs[q["key"]] = q["reference"]
        elif q["key"] in computed:
            refs[q["key"]] = computed[q["key"]]
    return refs


def check(case, values, refs):
    """Compare computed `values` with the references `refs` and the tolerances.

    Returns `(checked, failures)`: the number of quantities that carry a
    tolerance, and one message per quantity outside it.
    """
    checked = 0
    failures = []
    for q in case.get("quantity", []):
        if q["key"] not in refs or q["key"] not in values:
            continue
        ref = refs[q["key"]]
        value = values[q["key"]]
        abs_tol = q.get("abs_tolerance")
        rel_tol = q.get("tolerance", case.get("tolerance"))
        if abs_tol is not None:
            checked += 1
            if abs(value - ref) > abs_tol:
                failures.append(f"{q['key']}: |{value} - {ref}| > {abs_tol}")
        elif rel_tol is not None and ref != 0:
            checked += 1
            if abs(value - ref) > rel_tol * abs(ref):
                failures.append(f"{q['key']}: {value} vs {ref}, beyond {rel_tol:.2g}")
    return checked, failures


def fmt(value):
    return f"{value:.6g}"


def gap_to(value, ref):
    """The signed relative gap to `ref`, or the absolute one when `ref` is 0."""
    if ref == 0:
        return f"Δ = {value:.2g}"
    return f"{100 * (value - ref) / abs(ref):+.3g} %"


def cell(value, ref):
    if value is None:
        return "—"
    if ref is None:
        return fmt(value)
    return f"{fmt(value)} ({gap_to(value, ref)})"


def anchor(name):
    return name.lower()


def summary(cases):
    lines = [
        "## Summary",
        "",
        (
            "| Chapter | Case | Status | Largest gap to the reference "
            "| Largest gap pyrucast / Cast3M 2026 |"
        ),
        "|---|---|---|---|---|",
    ]
    counts = {"run": 0, "gap": 0, "pending": 0}
    for chapter, folder, case in cases:
        state = status(case, folder)
        counts[state] += 1
        link = f"[{case['name']}](#{anchor(case['name'])})"
        if state == "gap":
            what = "missing: " + "; ".join(case["gap"])
            lines.append(f"| {chapter['title']} | {link} | gap | {what} | |")
            continue
        if state == "pending":
            lines.append(f"| {chapter['title']} | {link} | pending | | |")
            continue
        values = read_json(folder / "results.json")["values"]
        castem = (read_json(folder / "castem2026.json") or {}).get("values", {})
        refs = references(case, folder)
        worst_ref = None
        worst_abs = None  # over the quantities whose reference is 0
        worst_castem = None
        for q in case["quantity"]:
            value = values.get(q["key"])
            if value is None:
                continue
            ref = refs.get(q["key"])
            if ref is not None and ref != 0:
                gap = abs(value - ref) / abs(ref)
                worst_ref = gap if worst_ref is None else max(worst_ref, gap)
            if ref == 0:
                gap = abs(value)
                worst_abs = gap if worst_abs is None else max(worst_abs, gap)
            other = castem.get(q["key"])
            # A quantity whose reference is 0 is an error measure: comparing
            # two small errors relatively says nothing.
            if other is not None and other != 0 and ref != 0:
                gap = abs(value - other) / abs(other)
                worst_castem = gap if worst_castem is None else max(worst_castem, gap)
        checked, failures = check(case, values, refs)
        verdict = "run"
        if checked:
            verdict = (
                "run, within tolerance" if not failures else "run, OUTSIDE tolerance"
            )
        parts = []
        if worst_ref is not None:
            parts.append(f"{100 * worst_ref:.3g} %")
        if worst_abs is not None:
            parts.append(f"Δ = {worst_abs:.2g}")
        ref_text = "; ".join(parts)
        castem_text = "" if worst_castem is None else f"{worst_castem:.1e}"
        lines.append(
            f"| {chapter['title']} | {link} | {verdict} | {ref_text} | {castem_text} |"
        )
    total = sum(counts.values())
    lines.insert(
        2,
        f"{total} cases: {counts['run']} computed by pyrucast, "
        f"{counts['gap']} not computable yet, {counts['pending']} pending.\n",
    )
    return lines


def feature_table(cases, field, title, intro):
    """A table of the strings listed under `field` in the cases, each with the
    cases that list it, most listed first."""
    listed = {}
    for _chapter, _folder, case in cases:
        for feature in case.get(field, []):
            listed.setdefault(feature, []).append(case["name"])
    lines = [f"## {title}", "", intro, "", "| Point | Cases | Count |", "|---|---|---|"]
    ranked = sorted(listed.items(), key=lambda item: (-len(item[1]), item[0]))
    for feature, names in ranked:
        links = ", ".join(f"[{n}](#{anchor(n)})" for n in names)
        lines.append(f"| {feature} | {links} | {len(names)} |")
    return lines


def sheet(chapter, folder, case):
    state = status(case, folder)
    rel = folder.relative_to(ROOT).as_posix()
    if state == "gap":
        model = "not available — missing: " + "; ".join(case["gap"])
    else:
        model = case.get("pyrucast", "")
    dgibi = (
        f"`dgibi/{case['dgibi']}`"
        if case.get("dgibi")
        else "not shipped with Cast3M 2026"
    )
    lines = [
        f"### {case['name']}",
        "",
        "#### Description sheet",
        "",
        "| | |",
        "|---|---|",
        f"| Test name | {case['name']} |",
        f"| Calculation type | {case['calculation_type']} |",
        f"| Finite element type (Cast3M) | {case['castem_element']} |",
        f"| pyrucast model | {model} |",
        f"| Reference | {case['source'] or 'no source cited in the original document'} |",
        f"| Cast3M version of the 2011 document | {case['castem_version']} |",
        f"| Cast3M 2026 `.dgibi` file | {dgibi} |",
        f"| Folder | [`{rel}/`]({rel}/) |",
        "",
        f"**Topic.** {case['topic'].strip()}",
        "",
        f"**Goal.** {case['goal'].strip()}",
        "",
        "**Model description.**",
        "",
        case["model"].strip(),
        "",
    ]
    if case.get("notes"):
        lines += [f"**Notes.** {case['notes'].strip()}", ""]
    if case.get("improvements"):
        lines += ["**Improvement points.**", ""]
        lines += [f"- {point}" for point in case["improvements"]] + [""]
    return lines


def results(folder, case):
    computed = read_json(folder / "results.json")
    castem = read_json(folder / "castem2026.json")
    values = computed["values"] if computed else {}
    castem_values = castem["values"] if castem else {}
    refs = references(case, folder)
    if not case.get("quantity"):
        return ["#### Results", "", "No compared quantity.", ""]
    lines = [
        "#### Results",
        "",
        (
            "| Quantity | Reference | Cast3M 2011 | Cast3M 2026 | pyrucast "
            "| pyrucast / Cast3M 2026 |"
        ),
        "|---|---|---|---|---|---|",
    ]
    for q in case.get("quantity", []):
        ref = refs.get(q["key"])
        label = f"{q['label']} ({q['unit']})" if q.get("unit") else q["label"]
        if "reference_probe" in q:
            label += " ¹"
        mine = values.get(q["key"])
        other = castem_values.get(q["key"])
        versus = ""
        if mine is not None and other is not None:
            if other == 0 or ref == 0:
                versus = f"Δ = {mine - other:.1e}"
            else:
                versus = f"{abs(mine - other) / abs(other):.1e}"
        pyrucast = cell(mine, ref)
        if status(case, folder) == "gap":
            pyrucast = "not available"
        lines.append(
            f"| {label} | {'—' if ref is None else fmt(ref)} "
            f"| {cell(q.get('castem_2011'), ref)} | {cell(other, ref)} "
            f"| {pyrucast} | {versus} |"
        )
    lines.append("")
    if any("reference_probe" in q for q in case.get("quantity", [])):
        lines += [
            "¹ Reference computed by the Cast3M 2026 `.dgibi` file from its analytical formula.",
            "",
        ]
    if case.get("tolerance_note"):
        lines += [f"Acceptance: {case['tolerance_note'].strip()}", ""]
    if castem and castem["status"] != "ok":
        lines += [f"Cast3M 2026 run: {castem['status']} — {castem['message']}", ""]
    if computed:
        checked, failures = check(case, values, refs)
        if checked and not failures:
            lines += [
                f"pyrucast: the {checked} checked quantities are within tolerance.",
                "",
            ]
        for failure in failures:
            lines += [f"pyrucast OUTSIDE tolerance: {failure}", ""]
    return lines


def figures_and_listing(folder):
    rel = folder.relative_to(ROOT).as_posix()
    lines = []
    figures = sorted(folder.glob("*.svg"))
    if figures:
        lines += ["#### pyrucast figures", ""]
        for figure in figures:
            lines += [f"![{figure.stem}]({rel}/{figure.name})", ""]
    script = folder / "run.py"
    if script.exists():
        lines += [
            "#### pyrucast listing",
            "",
            "<details><summary><code>run.py</code></summary>",
            "",
            "```python",
            script.read_text(encoding="utf-8").rstrip(),
            "```",
            "",
            "</details>",
            "",
        ]
    return lines


def main():
    cases = load_cases()
    lines = [HEADER]
    lines += summary(cases) + [""]
    lines += feature_table(
        cases,
        "gap",
        "Missing features",
        "Features pyrucast lacks for the cases it cannot compute yet, by number "
        "of cases blocked.",
    ) + [""]
    lines += feature_table(
        cases,
        "improvements",
        "Improvement points",
        "What writing the computed cases showed: an operator or an option "
        "pyrucast lacks to state the case as the `.dgibi` file does, or a difference with "
        "Cast3M to look into. The scripts use pyrucast as it is; each point is "
        "detailed in the case's notes.",
    ) + [""]
    current = None
    for chapter, folder, case in cases:
        if chapter is not current:
            current = chapter
            lines += [f"## {chapter['title']}", ""]
        lines += sheet(chapter, folder, case)
        lines += results(folder, case)
        lines += figures_and_listing(folder)
    text = "\n".join(lines).rstrip() + "\n"
    (ROOT / "README.md").write_text(text, encoding="utf-8")
    print(f"validation/README.md: {len(cases)} cases")


if __name__ == "__main__":
    main()
